#!/usr/bin/env python3
"""Generate Flutter capability constants from the authoritative JSON registry."""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "backend/app/data/capabilities.json"
TARGET = ROOT / "app/lib/generated/capabilities.g.dart"


def _dart_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def render() -> str:
    entries = json.loads(SOURCE.read_text(encoding="utf-8"))["capabilities"]
    lines = [
        "// GENERATED FROM backend/app/data/capabilities.json.",
        "// Do not edit this file by hand; run scripts/generate_capabilities.py.",
        "library;", "", "class DrugCapability {",
        "  const DrugCapability({", "    required this.drug,",
        "    required this.primaryGene,", "    required this.relevantGenes,",
        "    required this.evidenceDependencies,",
        "    required this.implementationStatus,",
        "    required this.guidanceCapable,", "    required this.limitation,",
        "    required this.explanationAvailable,", "    required this.uiAvailable,",
        "    required this.exportAvailable,", "  });", "",
        "  final String drug;", "  final String primaryGene;",
        "  final List<String> relevantGenes;",
        "  final List<String> evidenceDependencies;",
        "  final String implementationStatus;", "  final bool guidanceCapable;",
        "  final String limitation;", "  final bool explanationAvailable;",
        "  final bool uiAvailable;", "  final bool exportAvailable;", "",
        "  Map<String, dynamic> toExportJson() => <String, dynamic>{",
        "    'drug': drug,", "    'primary_gene': primaryGene,",
        "    'relevant_genes': relevantGenes,",
        "    'evidence_dependencies': evidenceDependencies,",
        "    'implementation_status': implementationStatus,",
        "    'guidance_capable': guidanceCapable,", "    'limitation': limitation,",
        "    'explanation_available': explanationAvailable,",
        "    'ui_available': uiAvailable,", "    'export_available': exportAvailable,",
        "  };", "}", "",
        "const List<DrugCapability> kDrugCapabilities = <DrugCapability>[",
    ]
    for entry in entries:
        relevant = ", ".join(_dart_string(v) for v in entry["relevant_genes"])
        dependencies = ", ".join(
            _dart_string(v) for v in entry["evidence_dependencies"]
        )
        lines.append(
            "  DrugCapability("
            f"drug: {_dart_string(entry['drug'])}, "
            f"primaryGene: {_dart_string(entry['primary_gene'])}, "
            f"relevantGenes: <String>[{relevant}], "
            f"evidenceDependencies: <String>[{dependencies}], "
            f"implementationStatus: {_dart_string(entry['implementation_status'])}, "
            f"guidanceCapable: {str(entry['guidance_capable']).lower()}, "
            f"limitation: {_dart_string(entry['limitation'])}, "
            f"explanationAvailable: {str(entry['explanation_available']).lower()}, "
            f"uiAvailable: {str(entry['ui_available']).lower()}, "
            f"exportAvailable: {str(entry['export_available']).lower()}),"
        )
    lines.extend(["];", "", "const List<String> kDemoDrugs = <String>["])
    lines.extend(
        f"  {_dart_string(entry['drug'])},"
        for entry in entries
        if entry["ui_available"]
    )
    lines.extend(["];", ""])
    lines.extend([
        "DrugCapability? capabilityForDrug(String drug) {",
        "  final String key = drug.trim().toLowerCase();",
        "  for (final DrugCapability capability in kDrugCapabilities) {",
        "    if (capability.drug == key) return capability;",
        "  }",
        "  return null;",
        "}",
        "",
    ])
    return "\n".join(lines)


if __name__ == "__main__":
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(render(), encoding="utf-8")
