#!/usr/bin/env python3
"""
Derive the GRCh38 reference base at every required position into
backend/app/data/reference_alleles.json (Phase 9 B6, audit finding F-02).

    python scripts/derive_reference_alleles.py --check   # exit 1 if it differs
    python scripts/derive_reference_alleles.py --write

A genotype is written relative to its REF allele. A file whose REF contradicts
GRCh38 at a required position was not made against the reference this analysis
reads, so its genotypes there mean something else (A4-09a/b, A4-22): PharmCAT
discards some such rows and reads others as reference without a word, and the
coverage gate, which keys evidence on (chrom, pos) alone, never saw it.

Source: PharmCAT's positions VCF, the file the required positions themselves
come from (scripts/build_position_requirements.py). The base kept is the first
base of its REF, which for an indel is the anchor base at POS, so it is the
reference base at POS whatever the variant. Every one is cross-checked against
the jar's allele definitions (`variants[].ref`), and derivation stops on any
disagreement: the two PharmCAT sources check each other.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import sys
import zipfile

from _common import REPO_ROOT

POSITIONS_VCF = REPO_ROOT / "test-data" / "reference" / "tools" / "pharmcat_positions_3.4.0.vcf.bgz"
JAR = REPO_ROOT / "test-data" / "reference" / "tools" / "pharmcat-3.4.0-all.jar"
REQUIREMENTS = REPO_ROOT / "backend" / "app" / "data" / "position_requirements.json"
OUT = REPO_ROOT / "backend" / "app" / "data" / "reference_alleles.json"
DEFINITION = "org/pharmgkb/pharmcat/definition/alleles/{gene}_translation.json"


def _sha256(path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def positions_vcf_refs() -> dict[tuple[str, int], tuple[str, str]]:
    """(chrom, pos) -> (REF, ID) for every row of PharmCAT's positions VCF."""
    refs: dict[tuple[str, int], tuple[str, str]] = {}
    with gzip.open(POSITIONS_VCF, "rt") as handle:  # BGZF is multi-member gzip
        for line in handle:
            if line.startswith("#"):
                continue
            chrom, pos, rsid, ref = line.split("\t")[:4]
            key = (chrom, int(pos))
            if key in refs and refs[key][0][:1] != ref[:1]:
                raise SystemExit(f"{chrom}:{pos}: two rows disagree on the reference base")
            refs.setdefault(key, (ref, rsid))
    return refs


def definition_refs(gene: str) -> dict[tuple[str, int], str]:
    with zipfile.ZipFile(JAR) as zf:
        data = json.loads(zf.read(DEFINITION.format(gene=gene)))
    return {(data["chromosome"], v["position"]): v["ref"] for v in data["variants"]}


def derive() -> dict:
    requirements = json.loads(REQUIREMENTS.read_text())["genes"]
    vcf = positions_vcf_refs()
    alleles: dict[str, dict] = {}
    for gene in sorted(requirements):
        defined = definition_refs(gene)
        for chrom, pos in requirements[gene]["positions"]:
            key = (chrom, pos)
            if key not in vcf:
                raise SystemExit(f"{gene} {chrom}:{pos} is required but not in the positions VCF")
            if key not in defined:
                raise SystemExit(f"{gene} {chrom}:{pos} is required but not in the jar's {gene} definition")
            ref, rsid = vcf[key]
            base = ref[:1].upper()
            if defined[key][:1].upper() != base:
                raise SystemExit(f"{gene} {chrom}:{pos}: positions VCF REF {ref}, definition ref {defined[key]}")
            label = f"{chrom}:{pos}"
            if label in alleles and alleles[label]["base"] != base:
                raise SystemExit(f"{label}: genes disagree on the reference base")
            alleles.setdefault(label, {"base": base, "gene": gene, "rsid": rsid if rsid != "." else ""})
    return {
        "_comment": (
            "GRCh38 reference base at every required position: the first base of "
            "the REF in PharmCAT's positions VCF, cross-checked against the jar's "
            "allele definitions. Generated by scripts/derive_reference_alleles.py "
            "— do not edit by hand."
        ),
        "positions_vcf": POSITIONS_VCF.name,
        "positions_vcf_sha256": _sha256(POSITIONS_VCF),
        "jar": JAR.name,
        "jar_sha256": _sha256(JAR),
        "genes": sorted(requirements),
        "count": len(alleles),
        "alleles": alleles,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    mode.add_argument("--write", action="store_true", help="rewrite the file")
    args = parser.parse_args()
    text = json.dumps(derive(), indent=2, sort_keys=True) + "\n"
    if args.check:
        same = OUT.is_file() and OUT.read_text() == text
        print("reference_alleles.json matches PharmCAT" if same else "reference_alleles.json DIFFERS from PharmCAT")
        return 0 if same else 1
    OUT.write_text(text)
    print(f"{json.loads(text)['count']} reference bases written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
