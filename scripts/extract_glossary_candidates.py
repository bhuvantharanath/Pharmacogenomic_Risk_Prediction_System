#!/usr/bin/env python3
"""
Extract domain vocabulary from every user-facing string, and measure the noise.

    python scripts/extract_glossary_candidates.py            # write the report
    python scripts/extract_glossary_candidates.py --fp-only  # just the FP rate

Writes `reports/glossary_candidates.md`: every candidate, how often it appears,
and one quoted line showing where. Terms already defined are listed separately
from terms that are not, because the second list is the finding.

The false-positive rate is measured against a vendored corpus of ordinary
English prose — see `--fp-only`. Every term the extractor flags there is wrong
by construction: the corpus contains no pharmacogenomics and no software
writing, so it has no domain vocabulary to find.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import glossary_lib as g  # noqa: E402


def measure_false_positives() -> tuple[int, int, list[str]]:
    """
    Distinct noun lemmas flagged in ordinary English, over distinct noun lemmas
    seen. Everything flagged is a false positive: there is nothing to find.
    """
    if not g.CONTROL_CORPUS.exists():
        return 0, 0, []

    nlp = g._nlp()
    text = g.CONTROL_CORPUS.read_text()
    seen: set[str] = set()
    flagged: set[str] = set()

    # Chunked: spaCy's default max_length is well below a pair of novels, and
    # raising it just to hold one string in memory buys nothing.
    for piece in [text[i:i + 90_000] for i in range(0, len(text), 90_000)]:
        for token in nlp(piece):
            if token.pos_ not in g.KEEP_POS:
                continue
            lemma = token.lemma_.lower().strip()
            if not g._WORDLIKE.match(lemma):
                continue
            seen.add(lemma)
            if g.zipf(lemma) < g.ZIPF_THRESHOLD:
                flagged.add(lemma)

    return len(flagged), len(seen), sorted(flagged)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--fp-only", action="store_true",
                    help="measure the false-positive rate and stop")
    args = ap.parse_args()

    if args.fp_only:
        flagged, seen, examples = measure_false_positives()
        rate = (flagged / seen * 100) if seen else 0.0
        print(f"ordinary-English control: {seen} distinct noun lemmas, "
              f"{flagged} flagged = {rate:.1f}% false positive")
        print("  sample:", ", ".join(examples[:25]))
        return 0

    snippets = g.collect_snippets()
    found = g.extract(snippets)
    phrases = g.extract_phrases(snippets)
    known = g.defined_forms()
    ordinary = g.decided_ordinary()
    pending = g.decided_defined()

    already = sorted(t for t in found if t in known)
    marked = sorted(t for t in found if t in ordinary)
    drafted = sorted(t for t in found if t in pending)
    gaps = g.undefined(found)

    flagged, seen, _ = measure_false_positives()
    fp_rate = (flagged / seen * 100) if seen else 0.0

    out = [
        "# Glossary candidates — extracted from the shipped strings",
        "",
        "Generated by `scripts/extract_glossary_candidates.py`. Do not edit by",
        "hand: re-run it. Decisions belong in `glossary_decisions.json`, written",
        "by `scripts/glossary_review.py` and attributed to whoever made them.",
        "",
        "## How these were found",
        "",
        f"Every string this project shows a user — {len(snippets)} of them, "
        f"{sum(len(s.text) for s in snippets):,} characters — was tagged with "
        "spaCy `en_core_web_sm`. Tokens tagged NOUN or PROPN were lemmatised, "
        f"and a lemma is a candidate when it occurs less than once per 10,000 "
        f"words in ordinary English (Zipf < {g.ZIPF_THRESHOLD}).",
        "",
        "No rule decides whether a word is biomedical, and no model judges its",
        "meaning. The extractor only knows what is rare. Everything rare goes to",
        "a person. The rule was recorded in `glossary_precommitment.md` before",
        "it was run.",
        "",
        "## Counts",
        "",
        "| | |",
        "| --- | ---: |",
        f"| candidates found | **{len(found)}** |",
        f"| already defined in the shipped glossary | {len(already)} |",
        f"| marked ordinary English by a reviewer | {len(marked)} |",
        f"| defined by a reviewer, not yet shipped | {len(drafted)} |",
        f"| **undefined and undecided** | **{len(gaps)}** |",
        "",
        f"False-positive rate on ordinary English: **{fp_rate:.1f}%** "
        f"({flagged} of {seen} distinct noun lemmas flagged in a corpus with no "
        "domain vocabulary in it).",
        "",
        "## Undefined and undecided",
        "",
        "This is the gap. The gate in `glossary_status.py` fails while this list",
        "is non-empty.",
        "",
    ]

    if gaps:
        out += ["| term | zipf | uses | where it appears |",
                "| --- | ---: | ---: | --- |"]
        for c in gaps:
            source, line = c.contexts[0] if c.contexts else ("", "")
            quoted = line.replace("|", "\\|")
            out.append(f"| `{c.term}` | {c.zipf:.2f} | {c.count} | "
                       f"<sub>{source}</sub><br>“{quoted}” |")
    else:
        out.append("_None. Every candidate has a definition or an explicit "
                   "decision._")

    buckets = g.triage({c.term: c for c in gaps}, snippets)
    out += ["## Triage", "",
            "Sorted mechanically before anyone writes a definition — roughly a",
            "fifth of what the extractor finds is not glossary work at all, and",
            "two of these categories are defects in the product rather than gaps",
            "in the documentation.", "",
            "| category | count | meaning |",
            "| --- | ---: | --- |"]
    for key, meaning in g.CATEGORIES.items():
        out.append(f"| **{key}** | {len(buckets[key])} | {meaning} |")
    out.append("")
    for key in ("B", "C", "D", "E"):
        if buckets[key]:
            out += [f"**{key}** — " + ", ".join(f"`{t}`" for t in buckets[key]), ""]

    if g.DROPPED_ARTIFACTS:
        out += ["## Dropped before triage — lemmatiser damage", "",
                "Never shown to a reviewer. A term nobody can define because it",
                "is not a word, or one that is only rare in a form the reader",
                "never sees.", "",
                "| lemma | why |", "| --- | --- |"]
        for term, why in sorted(g.DROPPED_ARTIFACTS.items()):
            out.append(f"| `{term}` | {why} |")
        out.append("")

    out += ["", "## Already defined", "",
            ", ".join(f"`{t}`" for t in already) or "_none_", ""]

    if marked:
        out += ["## Marked ordinary English by a reviewer", "",
                ", ".join(f"`{t}`" for t in marked), ""]

    out += ["## Multi-word candidates", "",
            "Noun chunks containing at least one candidate. A reader meets the",
            "phrase, not its rarest half, so these are offered to the reviewer",
            "alongside the single words.", ""]
    top = sorted(phrases.items(), key=lambda kv: (-kv[1], kv[0]))[:40]
    out += [", ".join(f"`{p}` ({n})" for p, n in top) or "_none_", ""]

    (g.REPO / "reports" / "glossary_candidates.md").write_text("\n".join(out) + "\n")

    print(f"candidates      {len(found)}")
    print(f"  defined       {len(already)}")
    print(f"  ordinary      {len(marked)}")
    print(f"  drafted       {len(drafted)}")
    print(f"  UNDEFINED     {len(gaps)}")
    print(f"false positives {fp_rate:.1f}% on ordinary English")
    print("wrote reports/glossary_candidates.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
