#!/usr/bin/env python3
"""
Generate the client's South Asian population context from the project's own measurement (Phase 9 B11).

    python scripts/generate_population_context.py           # write the Dart file
    python scripts/generate_population_context.py --check   # exit 1 if the committed file differs

Reads, never edits:
  reports/sas_frequencies.json          phenotype counts per 1000 Genomes SAS cohort, and pooled (n=601)
  reports/sas_deviation_filtered.json   positions present per gene in the measured slice
  reports/sas_cohort_expansion.md       the measurement date
Writes app/lib/generated/population_context.g.dart: the figures as a JSON string the client parses.

No figure is typed here. Reduced function is Poor plus Intermediate Metabolizer, or Poor plus Decreased Function
for SLCO1B1. Indeterminate, "No Result" and "n/a" stay in the denominator and are never counted as reduced, as in
the report's own CYP2C19 figure. Intervals are 95% Wilson. The figures are context only: the app never uses them
for a call or a label.
"""

from __future__ import annotations

import argparse
import json
import math
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
FREQUENCIES = REPO / "reports/sas_frequencies.json"
DEVIATIONS = REPO / "reports/sas_deviation_filtered.json"
REPORT = REPO / "reports/sas_cohort_expansion.md"
OUT = REPO / "app/lib/generated/population_context.g.dart"

METABOLIZER = ("Poor Metabolizer", "Intermediate Metabolizer")
REDUCED = {
    "CYP2C19": METABOLIZER,
    "CYP2C9": METABOLIZER,
    "SLCO1B1": ("Poor Function", "Decreased Function"),
    "TPMT": METABOLIZER,
    "NUDT15": METABOLIZER,
    "DPYD": METABOLIZER,
}
UNCERTAIN = ("Indeterminate", "No Result", "n/a")
#: The cohorts, largest first (reports/sas_cohort_expansion.md).
COHORTS = ("PJL", "BEB", "STU", "ITU", "GIH")
Z = 1.96


def wilson(k: int, n: int, z: float = Z) -> tuple[float, float]:
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return centre - half, centre + half


def rate(phenotypes: dict[str, int], reduced: tuple[str, ...]) -> dict:
    n = sum(phenotypes.values())
    k = sum(phenotypes.get(name, 0) for name in reduced)
    low, high = wilson(k, n)
    return {"reduced": k, "n": n, "percent": f"{100 * k / n:.1f}",
            "low": f"{100 * low:.1f}", "high": f"{100 * high:.1f}"}


def build() -> dict:
    frequencies = json.loads(FREQUENCIES.read_text())
    deviations = json.loads(DEVIATIONS.read_text())
    measured = re.search(r"Measured \*\*(\d{4}-\d{2}-\d{2})\*\*", REPORT.read_text()).group(1)
    coverage = {row["gene"]: (row["positions_present"], row["positions_required"])
                for row in deviations["input_artifacts"]}
    genes = {}
    for gene, reduced in REDUCED.items():
        pooled = frequencies["pooled_sas"][gene]["phenotypes"]
        present, required = coverage.get(gene, (None, None))
        genes[gene] = {
            "reduced_definition": " or ".join(reduced),
            "pooled": rate(pooled, reduced),
            "cohorts": [{"cohort": cohort, **rate(
                frequencies["genes"][gene]["populations"][cohort]["phenotypes"], reduced)}
                for cohort in COHORTS],
            "positions_present": present,
            "positions_required": required,
            "uncertain": {name: pooled.get(name, 0) for name in UNCERTAIN if pooled.get(name, 0)},
        }
    return {"measured": measured, "samples": frequencies["n_reports"], "cohorts": list(COHORTS), "genes": genes}


def render(data: dict) -> str:
    body = json.dumps(data, indent=1, ensure_ascii=False)
    assert "'''" not in body
    return (
        "// GENERATED FROM reports/sas_frequencies.json and reports/sas_deviation_filtered.json.\n"
        "// Do not edit this file by hand; run scripts/generate_population_context.py.\n"
        "library;\n"
        "\n"
        f"/// South Asian reduced-function context, measured {data['measured']} (Phase 9 B11).\n"
        "/// Context only: never used for a call or a label.\n"
        "const String kSouthAsianContextJson = r'''\n"
        f"{body}\n"
        "''';\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    args = parser.parse_args(argv)
    text = render(build())
    if args.check:
        if OUT.read_text() != text:
            print(f"{OUT.relative_to(REPO)} differs from what the reports give; regenerate it", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(REPO)} matches the reports")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
