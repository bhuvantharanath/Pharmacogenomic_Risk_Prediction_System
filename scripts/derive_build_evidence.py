#!/usr/bin/env python3
"""
Vendor PharmCAT's build evidence into `backend/app/data/build_evidence.json`.

WHAT PHARMCAT ACTUALLY SHIPS — and what it does not

The remediation brief asked for build inference from CONTIG LENGTHS, verified
against PharmCAT's data. PharmCAT does not ship contig lengths. Checked:

  definition/chr_build_mapping.tsv    build, chromosome, chr name, RefSeq accession
  pharmcat_positions_3.4.0.vcf.bgz    ##contig=<ID=chrN,assembly=GRCh38.p14,
                                      species="Homo sapiens">   — no length field
  (no .fai, .dict, or chrom.sizes anywhere in the jar)

So contig lengths could only have come from memory or an outside source, which
is exactly what the brief forbade. What PharmCAT does ship is better for the
purpose: a build-to-RefSeq-accession mapping covering b36/b37/b38. An accession
is unambiguous — `NC_000001.11` IS GRCh38 chr1 — where a length has to be
matched against a remembered table.

Detection therefore uses, in order of strength:

  1. RefSeq accession in a `##contig` line   -> exact build, PharmCAT-sourced
  2. `species=` in a `##contig` line         -> refuse non-human
  3. `assembly=` / `##reference=` text       -> declared build (weakest; a
                                                declaration can be wrong)

Contig length is NOT used, and the reason is recorded here rather than left as
a silent omission.
"""

from __future__ import annotations

import json
import pathlib
import zipfile

REPO = pathlib.Path(__file__).resolve().parents[1]
JAR = REPO / "test-data/reference/tools/pharmcat-3.4.0-all.jar"
MAPPING = "org/pharmgkb/pharmcat/definition/chr_build_mapping.tsv"
BUILD_NAMES = {"b36": "GRCh36", "b37": "GRCh37", "b38": "GRCh38"}


def main() -> int:
    rows = zipfile.ZipFile(JAR).read(MAPPING).decode().splitlines()
    accessions: dict[str, str] = {}
    contigs: dict[str, dict[str, str]] = {}
    for line in rows:
        if not line.strip():
            continue
        build, _num, name, accession = line.split("\t")
        accessions[accession] = BUILD_NAMES[build]
        contigs.setdefault(BUILD_NAMES[build], {})[name] = accession

    (REPO / "backend/app/data/build_evidence.json").write_text(json.dumps({
        "_comment": (
            "Build evidence derived from PharmCAT's own "
            "definition/chr_build_mapping.tsv. Generated by "
            "scripts/derive_build_evidence.py — do not edit by hand. NOTE: "
            "PharmCAT ships NO contig LENGTHS; it ships RefSeq accessions per "
            "build, which are unambiguous and are used instead."
        ),
        "source": MAPPING,
        "jar": JAR.name,
        "required_build": "GRCh38",
        "accession_to_build": accessions,
        "build_to_contigs": contigs,
    }, indent=2, sort_keys=True) + "\n")
    print(f"{len(accessions)} accessions across {sorted(contigs)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
