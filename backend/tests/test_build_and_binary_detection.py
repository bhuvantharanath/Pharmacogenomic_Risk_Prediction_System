def test_a_nul_byte_in_a_data_row_is_refused() -> None:
    payload = _vcf('##reference=GRCh38\n') + b"chr10\t100\t.\tA\x00\tG\t.\tPASS\t.\tGT\t0/1\n"
    message = _expect(payload, VcfErrorCode.NOT_VCF)
    assert "NUL byte" in message
    # Says WHERE, so a large file can be inspected rather than re-exported blind.
    assert "line" in message.lower()


def test_a_nul_byte_deep_in_a_large_file_is_still_caught() -> None:
    """
    The whole point of scanning the whole file: a prefix check would pass this.
    """
    payload = _vcf('##reference=GRCh38\n') + (ROW.encode() * 5000) \
        + b"chr10\t100\t.\tA\x00\tG\t.\tPASS\t.\tGT\t0/1\n"
    _expect(payload, VcfErrorCode.NOT_VCF)


def test_a_clean_file_is_unaffected() -> None:
    meta = validate_vcf(
        _vcf('##reference=GRCh38\n',
             '##contig=<ID=chr10,assembly=GRCh38.p14,species="Homo sapiens">\n'),
        filename="clean.vcf")
    assert meta.reference_build is ReferenceBuild.GRCH38
    assert meta.variant_count == 1
