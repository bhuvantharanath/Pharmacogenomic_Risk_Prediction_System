"""
Species, reference build, and binary content — refusals, not warnings.

WHAT THE HOSTILE-INPUT SUITE FOUND

Two files were accepted that should not have been: a GRCm39 / `Mus musculus`
VCF, and a file with a NUL byte in a data row. Neither was a 5xx or a hang — the
survivability contract held — but both were answered rather than refused.

  mouse    build detection only distinguished GRCh37 from GRCh38, so anything
           else fell to UNKNOWN, which warns. Every position lookup then missed
           and the user got a screen of confident Unknowns: wasted work
           presented as an answer.
  NUL      the binary check is a UTF-8 decode, and NUL is valid UTF-8. A file
           that was text at the top and corrupt further down passed.

WHERE THE BUILD EVIDENCE COMES FROM

`backend/app/data/build_evidence.json`, generated by
`scripts/derive_build_evidence.py` from PharmCAT's own
`definition/chr_build_mapping.tsv`.

**PharmCAT ships no contig lengths.** The remediation brief asked for length-
based inference verified against PharmCAT's data; that data does not exist —
`chr_build_mapping.tsv` carries RefSeq accessions, the positions VCF header
carries assembly and species with no `length=`, and there is no .fai/.dict in
the jar. Lengths could only have come from memory. Accessions are what PharmCAT
actually ships and are strictly stronger: `NC_000001.11` IS GRCh38 chr1.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from app.vcf_validation import (
    ReferenceBuild,
    VcfErrorCode,
    VcfValidationError,
    detect_build_from_accessions,
    detect_species,
    validate_vcf,
)

ROW = "chr10\t94842866\t.\tA\tG\t.\tPASS\t.\tGT\t0/1\n"
COLUMNS = "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tSAMPLE\n"


def _vcf(*header: str, row: str = ROW) -> bytes:
    return ("##fileformat=VCFv4.2\n" + "".join(header) + COLUMNS + row).encode()


def _expect(payload: bytes, code: VcfErrorCode, name: str = "t.vcf") -> str:
    with pytest.raises(VcfValidationError) as exc:
        validate_vcf(payload, filename=name)
    assert exc.value.code is code, f"got {exc.value.code}"
    return exc.value.message


# --------------------------------------------------------------------------- #
# The evidence is derived, not typed
# --------------------------------------------------------------------------- #

def test_the_build_evidence_came_from_pharmcats_own_mapping() -> None:
    data = json.loads(
        (Path(__file__).resolve().parents[1] / "app/data/build_evidence.json")
        .read_text())
    assert data["source"].endswith("chr_build_mapping.tsv")
    assert data["required_build"] == "GRCh38"
    # b36/b37/b38 across 24 contigs each.
    assert len(data["accession_to_build"]) == 74
    assert data["accession_to_build"]["NC_000001.11"] == "GRCh38"
    assert data["accession_to_build"]["NC_000001.10"] == "GRCh37"


def test_no_contig_length_is_hardcoded_anywhere() -> None:
    """
    Sabotage check on the method. PharmCAT ships no lengths, so a length
    appearing in the validator means somebody typed one from memory — exactly
    what the derived approach exists to avoid.
    """
    source = (Path(__file__).resolve().parents[1] / "app/vcf_validation.py"
              ).read_text()
    for length in ("248956422", "249250621", "242193529", "243199373"):
        assert length not in source, (
            f"contig length {length} is hardcoded — PharmCAT ships no lengths, "
            f"so this came from memory")


