def test_grch37_declared_by_filename_is_refused() -> None:
    message = _expect(_vcf("##reference=human_g1k_v37.fasta\n"),
                      VcfErrorCode.UNSUPPORTED_REFERENCE_BUILD)
    assert "GRCh37" in message and "GRCh38" in message


def test_grch37_detected_by_refseq_accession_is_refused() -> None:
    """
    The stronger signal. A file can declare GRCh38 in `##reference` and carry
    GRCh37 accessions; the accession is the fact.
    """
    _expect(_vcf('##contig=<ID=NC_000001.10,species="Homo sapiens">\n'),
            VcfErrorCode.UNSUPPORTED_REFERENCE_BUILD)


def test_grch38_by_accession_is_accepted() -> None:
    meta = validate_vcf(
        _vcf('##contig=<ID=NC_000001.11,species="Homo sapiens">\n'),
        filename="acc.vcf")
    assert meta.reference_build is ReferenceBuild.GRCH38
    assert meta.warnings == []


def test_a_headerless_grch38_vcf_still_works() -> None:
    """
    Nothing to infer from -> warn, do not refuse. Most real VCFs declare
    nothing, and refusing them would reject the common case to catch the rare
    one.
    """
    meta = validate_vcf(_vcf(), filename="bare.vcf")
    assert meta.reference_build is ReferenceBuild.UNKNOWN
    assert any("build" in w.lower() or "grch38" in w.lower()
               for w in meta.warnings), meta.warnings


def test_accessions_from_two_builds_are_not_treated_as_a_build() -> None:
    assert detect_build_from_accessions(
        ["##contig=<ID=NC_000001.10>", "##contig=<ID=NC_000002.12>"]) is None


