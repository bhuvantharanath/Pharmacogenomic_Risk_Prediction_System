def test_a_mouse_vcf_is_refused() -> None:
    message = _expect(
        _vcf('##reference=GRCm39\n',
             '##contig=<ID=chr10,assembly=GRCm39,species="Mus musculus">\n'),
        VcfErrorCode.NON_HUMAN_GENOME)
    # Names what was detected and what is needed.
    assert "Mus musculus" in message
    assert "GRCh38" in message
    # And does NOT suggest a liftover, which would be useless advice here.
    assert "convert" not in message.lower()


@pytest.mark.parametrize("declared", ["Homo sapiens", "human", "H. sapiens"])
def test_human_spellings_are_accepted(declared: str) -> None:
    meta = validate_vcf(
        _vcf(f'##contig=<ID=chr10,assembly=GRCh38.p14,species="{declared}">\n'),
        filename="human.vcf")
    assert meta.reference_build is ReferenceBuild.GRCH38


def test_a_file_declaring_no_species_is_not_refused_for_it() -> None:
    """Warn-only where there is genuinely nothing to infer from."""
    assert detect_species(["##contig=<ID=chr10>"]) is None


